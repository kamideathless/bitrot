export function measure(text, { font = FONT, scale = 1, tracking = 0 } = {}) {
  const adv = (font.w + font.gap + tracking) * scale;
  return Math.max(0, text.length * adv - (font.gap + tracking) * scale);
}

export function textHeight({ font = FONT, scale = 1 } = {}) {
  return font.h * scale;
}

/**
 * Draw text into a Gfx buffer.
 * opts: { font, scale, v (0|1), tracking, shadow, outline, invert }
 */
export function drawText(g, text, x, y, opts = {}) {
  const {
    font = FONT,
    scale = 1,
    v = 1,
    tracking = 0,
    shadow = false,
    outline = false,
    invert = false,
  } = opts;
  const str = String(text).toUpperCase();

  // Layout probe. Tests switch this on to catch strings that collide with each
  // other or run off the screen; it costs nothing when the array is absent.
  const trace = globalThis.__BITROT_TEXT_TRACE__;
  if (trace && str.trim()) {
    trace.push({
      text: str,
      x: Math.round(x),
      y: Math.round(y),
      w: measure(str, { font, scale, tracking }),
      h: font.h * scale,
    });
  }

  const adv = (font.w + font.gap + tracking) * scale;
  let cx = Math.round(x);
  const cy = Math.round(y);
  const alt = v ? 0 : 1;

  for (let i = 0; i < str.length; i++) {
    const glyph = font.glyphs.get(str[i]) || font.glyphs.get('?');
    if (glyph) {
      if (outline) {
        for (let oy = -1; oy <= 1; oy++) {
          for (let ox = -1; ox <= 1; ox++) {
            if (ox === 0 && oy === 0) continue;
            blitGlyph(g, glyph, font, cx + ox * scale, cy + oy * scale, scale, alt, false);
          }
        }
      } else if (shadow) {
        blitGlyph(g, glyph, font, cx + scale, cy + scale, scale, alt, false);
      }
      blitGlyph(g, glyph, font, cx, cy, scale, v, invert);
    }
    cx += adv;
  }
  return cx - (font.gap + tracking) * scale;
}

function blitGlyph(g, glyph, font, x, y, scale, v, invert) {
  const { w, h } = font;
  if (scale === 1) {
    for (let gy = 0; gy < h; gy++) {
      const row = gy * w;
      for (let gx = 0; gx < w; gx++) {
        if (!glyph[row + gx]) continue;
        if (invert) g.invertPx(x + gx, y + gy);
        else g.px(x + gx, y + gy, v);
      }
    }
    return;
  }
  for (let gy = 0; gy < h; gy++) {
    const row = gy * w;
    for (let gx = 0; gx < w; gx++) {
      if (!glyph[row + gx]) continue;
      if (invert) g.invertRect(x + gx * scale, y + gy * scale, scale, scale);
      else g.rect(x + gx * scale, y + gy * scale, scale, scale, v);
    }
  }
}

/** Centre text horizontally inside [x, x+w). */
export function drawTextCentered(g, text, x, w, y, opts = {}) {
  const tw = measure(String(text), opts);
  return drawText(g, text, Math.round(x + (w - tw) / 2), y, opts);
}

/** Right-align text so it ends at `right`. */
export function drawTextRight(g, text, right, y, opts = {}) {
  const tw = measure(String(text), opts);
  return drawText(g, text, Math.round(right - tw), y, opts);
}

/** Naive word wrap. Returns array of lines. */
export function wrapText(text, maxWidth, opts = {}) {
  const words = String(text).toUpperCase().split(/\s+/).filter(Boolean);
  const lines = [];
  let line = '';
  for (const word of words) {
    const candidate = line ? line + ' ' + word : word;
    if (measure(candidate, opts) <= maxWidth || !line) {
      line = candidate;
    } else {
      lines.push(line);
      line = word;
    }
  }
  if (line) lines.push(line);
  return lines;
}
