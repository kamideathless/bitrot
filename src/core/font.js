function compile(table, w, h) {
  const out = new Map();
  for (const ch of Object.keys(table)) {
    const rows = table[ch].split(',');
    if (rows.length !== h) throw new Error(`font glyph "${ch}" has ${rows.length} rows, expected ${h}`);
    const data = new Uint8Array(w * h);
    for (let y = 0; y < h; y++) {
      if (rows[y].length !== w) throw new Error(`font glyph "${ch}" row ${y} is ${rows[y].length} wide, expected ${w}`);
      for (let x = 0; x < w; x++) if (rows[y][x] === '#') data[y * w + x] = 1;
    }
    out.set(ch, data);
  }
  return out;
}

// Typographic characters that would otherwise fall back to "?".
const ALIASES = {
  '—': '-',   // em dash
  '–': '-',   // en dash
  '−': '-',   // minus sign
  '‘': "'", '’': "'",
  '“': '"', '”': '"',
  '·': '.', '•': '.',
  '×': '*',
  '…': '.',
  ' ': ' ',
};

function withAliases(glyphs) {
  for (const [from, to] of Object.entries(ALIASES)) {
    const g = glyphs.get(to);
    if (g) glyphs.set(from, g);
  }
  return glyphs;
}

export const FONT = { w: 5, h: 7, glyphs: withAliases(compile(G5, 5, 7)), gap: 1 };
export const MICRO = { w: 4, h: 6, glyphs: withAliases(compile(G3, 4, 6)), gap: 1 };

